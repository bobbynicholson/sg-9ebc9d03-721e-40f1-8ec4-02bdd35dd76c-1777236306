-- Reference table: SARS deductibility rules tailored to the
-- expenses a SA catering company actually runs through till slips.
-- Global to all tenants -- the rules come from the Income Tax Act
-- and VAT Act, not company preference. Companies tag individual
-- receipt lines against these rules; AI uses match_keywords to
-- pre-fill the suggestion.

CREATE TABLE IF NOT EXISTS public.sa_tax_deductibility_rules (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  category_code text UNIQUE NOT NULL,
  display_name text NOT NULL,
  group_label text NOT NULL,
  deductibility text NOT NULL CHECK (deductibility IN ('deductible','partial','non_deductible')),
  vat_input_claimable text NOT NULL CHECK (vat_input_claimable IN ('claimable','not_claimable','depends')),
  treatment text NOT NULL CHECK (treatment IN ('expense','capital','mixed','non_allowed')),
  capital_threshold_rand numeric(10,2),
  match_keywords text[] NOT NULL DEFAULT '{}',
  example_items text[] NOT NULL DEFAULT '{}',
  legal_reference text,
  notes text,
  display_order int NOT NULL DEFAULT 100,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.sa_tax_deductibility_rules ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "sa_tax_rules_read_all" ON public.sa_tax_deductibility_rules;
CREATE POLICY "sa_tax_rules_read_all" ON public.sa_tax_deductibility_rules FOR SELECT USING (true);

CREATE INDEX IF NOT EXISTS idx_sa_tax_rules_keywords ON public.sa_tax_deductibility_rules USING GIN (match_keywords);
CREATE INDEX IF NOT EXISTS idx_sa_tax_rules_active ON public.sa_tax_deductibility_rules (is_active, display_order);

