import { readFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
const env = Object.fromEntries(readFileSync(".env.local","utf8").split(/\r?\n/).filter(l=>l&&!l.startsWith("#")&&l.includes("=")).map(l=>{const i=l.indexOf("=");return [l.slice(0,i).trim(),l.slice(i+1).trim().replace(/^["']|["']$/g,"")];}));
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY, { auth:{persistSession:false} });
const OID="5b0bc5a4-a33f-417f-bbfc-c046aa1de14a";
const g = async (t,col,val,sel="*") => { try { const {data,error}=await sb.from(t).select(sel).eq(col,val); return error?{__e:error.message}:(data||[]); } catch(e){ return {__e:String(e)}; } };
const { data: o } = await sb.from("orders").select("*").eq("id",OID).single();
const invoices = await g("invoices","order_id",OID,"id,total_amount,created_at,sent_at");
const paysByInv = invoices.__e ? [] : (await Promise.all(invoices.map(i=>g("payments","invoice_id",i.id,"payment_type,status,amount,processed_at")))).flat();
const prep = await g("kitchen_prep_tasks","order_id",OID,"status,started_at,completed_at");
const da = await g("driver_assignments","order_id",OID,"assignment_type,status,created_at,completed_at");
const eb = await g("equipment_bookings","order_id",OID,"equipment_id");
const cj = await g("cleaning_jobs","triggered_by_event_id",OID,"status,actual_end");
const yes=(b)=>b?"DONE":"";
const has=(a)=>Array.isArray(a)&&a.length>0;
const prepArr = has(prep)?prep:[]; const prepDone=prepArr.filter(t=>t.status==="done").length; const prepTot=prepArr.filter(t=>t.status!=="skipped").length;
const daArr = has(da)?da:[]; const coll=daArr.find(a=>a.assignment_type==="collection");
const cjArr = has(cj)?cj.filter(j=>j.status!=="cancelled"):[];
const hasDeposit=Number(o.deposit_amount||0)>0; const hasBalance=Number(o.balance_amount||0)>0;
const hasHire=false; const hasOwned=has(eb)&&eb.some(b=>b.equipment_id);
const S=[];
const add=(n,st)=>S.push([n,st]);
add("1 Quote accepted", o.quote_id?"DONE":"n/a");
add("2 Order created", yes(!!o.created_at));
add("3 Deposit invoice", hasDeposit? yes(!invoices.__e&&invoices.some(i=>Number(i.total_amount)>0)):"n/a");
add("4 Deposit paid", hasDeposit? yes(!!o.deposit_paid):"n/a");
add("5 Confirmed", yes(!!o.confirmed_at || (o.status&&!["pending","draft"].includes(o.status))));
add("6 Hire booked", hasHire?"?":"n/a");
add("7 Hire collected", hasHire?"?":"n/a");
add("8 Pre-event cleaning", hasOwned?"upcoming(no col)":"n/a");
add("9 Kitchen prep", prepTot? (prepDone>=prepTot?"DONE":(prepArr.some(t=>t.status==="in_progress"||t.started_at)||o.prep_started_at?`CURRENT ${prepDone}/${prepTot}`:`upcoming ${prepDone}/${prepTot}`)) : "upcoming(no tasks)");
add("10 Ready for dispatch", yes(!!o.ready_at||["ready","in_transit","delivered","completed"].includes(o.status)||(prepTot&&prepDone>=prepTot)));
add("11 Driver assigned", yes(!!o.assigned_driver_id||daArr.some(a=>["delivery","both"].includes(a.assignment_type))));
add("12 On the road", o.status==="in_transit"||o.picked_up_at?"CURRENT/started":["delivered","completed"].includes(o.status)?"DONE":"upcoming");
add("13 Delivered", yes(!!o.delivered_at||["delivered","completed"].includes(o.status)));
add("14 Collection scheduled", o.equipment_return_method||has(eb)? yes(!!coll):"n/a");
add("15 Equipment back", o.equipment_return_method||has(eb)? yes(coll&&coll.status==="completed"):"n/a");
add("16 Post-event cleaning", (hasOwned)? (cjArr.length? (cjArr.every(j=>j.status==="complete")?"DONE":"current/upcoming"):"upcoming(no jobs)") : "n/a");
add("17 Final invoice", yes(!invoices.__e&&has(invoices)));
add("18 Invoice sent", yes(!invoices.__e&&invoices.some(i=>i.sent_at)));
add("19 Balance paid", hasBalance? yes(!!o.balance_paid):"n/a");
add("20 Receipt issued", hasBalance?"upcoming":"n/a");
add("21 Completed", yes(o.status==="completed"||!!o.completed_at));
add("22 Thank-you sent", "upcoming");
console.log(`ORD ${o.order_number}  status=${o.status} payment=${o.payment_status} event=${o.event_date}`);
console.log(`deposit_paid=${o.deposit_paid} balance_paid=${o.balance_paid} driver=${o.assigned_driver_id||"-"} delivered_at=${o.delivered_at||"-"}`);
console.log(`prep tasks: ${prepArr.length} (${prepDone} done)  driver_assignments: ${daArr.length}  equip_bookings: ${eb.__e?eb.__e:eb.length}  cleaning_jobs: ${cj.__e?cj.__e:cjArr.length}  invoices: ${invoices.__e?invoices.__e:invoices.length}`);
console.log("----- 22-STAGE TIMELINE -----");
for(const [n,st] of S) console.log(` ${st.startsWith("DONE")?"[x]":st.startsWith("CURRENT")||st.includes("current")?"[>]":st==="n/a"?"[-]":"[ ]"} ${n.padEnd(26)} ${st}`);
