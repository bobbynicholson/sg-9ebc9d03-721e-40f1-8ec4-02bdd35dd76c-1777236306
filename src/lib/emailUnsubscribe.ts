/**
 * Email unsubscribe token helpers.
 *
 * Per-recipient email suppression compliance (docs/notifications.md
 * follow-up 6.6). Every outgoing email needs a one-click unsubscribe
 * link in the footer; clicking it inserts the recipient into
 * blocked_contacts so the next emailService.sendEmail() call for
 * that company + email short-circuits before hitting the provider.
 *
 * The token is `base64url(email|companyId|hmac)` where hmac is
 * HMAC-SHA256 of `${email}:${companyId}` with the unsubscribe
 * signing secret. This avoids a per-email tokens table - the link
 * is deterministic, stateless, and can be regenerated by the
 * template renderer without round-tripping the DB.
 *
 * Secret resolution: prefers EMAIL_UNSUBSCRIBE_SECRET, falls back
 * to CRON_SECRET (an existing required env var) so deployments
 * don't need a new env var to start using this. Production deploys
 * should set EMAIL_UNSUBSCRIBE_SECRET explicitly so unsubscribe
 * links don't invalidate when cron secrets rotate.
 */

// Bare "crypto" (no `node:` prefix) - the prefixed form trips webpack
// when this module gets pulled into a client-eligible bundle chain via
// emailService.ts -> invoiceGenerationService.ts -> client components.
// Without the prefix, webpack resolves to Node's built-in on the
// server and to an empty stub on the client. The functions below are
// only ever invoked from server-side paths (api routes, cron jobs,
// the send-email handler), so the client-side stub is never executed.
import crypto from "crypto";

function getSecret(): string {
  return (
    process.env.EMAIL_UNSUBSCRIBE_SECRET ||
    process.env.CRON_SECRET ||
    "dev-unsubscribe-secret"
  );
}

function sign(email: string, companyId: string): string {
  return crypto
    .createHmac("sha256", getSecret())
    .update(`${email.toLowerCase().trim()}:${companyId}`)
    .digest("hex");
}

export function mintUnsubscribeToken(email: string, companyId: string): string {
  const cleanEmail = email.toLowerCase().trim();
  const hmac = sign(cleanEmail, companyId);
  const raw = `${cleanEmail}|${companyId}|${hmac}`;
  return Buffer.from(raw, "utf8").toString("base64url");
}

export interface DecodedUnsubscribeToken {
  email: string;
  companyId: string;
  valid: boolean;
}

export function verifyUnsubscribeToken(token: string): DecodedUnsubscribeToken {
  try {
    const raw = Buffer.from(token, "base64url").toString("utf8");
    const parts = raw.split("|");
    if (parts.length !== 3) return { email: "", companyId: "", valid: false };
    const [email, companyId, hmac] = parts;
    const expected = sign(email, companyId);
    // Constant-time comparison to defeat timing oracles.
    const a = Buffer.from(hmac, "hex");
    const b = Buffer.from(expected, "hex");
    const valid =
      a.length === b.length && crypto.timingSafeEqual(a, b);
    return { email, companyId, valid };
  } catch {
    return { email: "", companyId: "", valid: false };
  }
}

/**
 * Build the public unsubscribe URL for an outgoing email.
 *
 * Templates should call this and embed the returned URL in their
 * footer, like:
 *   <a href="{unsubscribeUrl}">Unsubscribe</a>
 */
export function buildUnsubscribeUrl(
  baseUrl: string,
  email: string,
  companyId: string,
): string {
  const token = mintUnsubscribeToken(email, companyId);
  return `${baseUrl.replace(/\/$/, "")}/u/${token}`;
}
