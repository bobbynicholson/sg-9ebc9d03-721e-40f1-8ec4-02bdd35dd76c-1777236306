import { readFileSync } from 'node:fs';
import { chromium } from 'playwright';
import { createClient } from '@supabase/supabase-js';
const env = Object.fromEntries(readFileSync('.env.local','utf8').split(/\r?\n/).filter(l=>l.includes('=')&&!l.startsWith('#')).map(l=>{const i=l.indexOf('=');return [l.slice(0,i).trim(), l.slice(i+1).trim().replace(/^"|"$/g,'')]}));
const sb = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SERVICE_ROLE_KEY);
const { data: q } = await sb.from('quotes').select('id').eq('quote_number', 'QUO-000004').eq('company_id', '1417901f-2a08-4fd0-a264-29f47ce371cb').single();
const cache = JSON.parse(readFileSync('tmp/ui-normalization/.session-cache.json', 'utf8'));
const browser = await chromium.launch({ executablePath: 'C:/Users/raj/AppData/Local/ms-playwright/chromium-1228/chrome-win64/chrome.exe' });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
await ctx.addCookies(cache['raj267748@gmail.com'].cookies);
await ctx.route('**/*', (r) => (['GET', 'HEAD', 'OPTIONS'].includes(r.request().method()) || r.request().url().includes('/auth/v1/')) ? r.continue() : r.abort());
const page = await ctx.newPage();
await page.goto(`http://localhost:3002/raj267748-payfast-test/admin/quotes/new?fromQuoteId=${q.id}`, { timeout: 120000 });
await page.waitForSelector('#quote-menu-items', { timeout: 120000 });
await page.waitForTimeout(6000);
const headings = await page.locator('#quote-menu-items h4').allTextContents();
const waiter = await page.locator('text=Include on-site waiter service').locator('xpath=preceding::input[@type="checkbox"][1] | following::input[@type="checkbox"][1]').first().isChecked().catch(() => 'n/a');
console.log('COURSE HEADINGS:', JSON.stringify(headings), 'WAITER TICKED:', waiter);
await page.locator('#quote-menu-items').screenshot({ path: 'tmp/embedchk/shots3/quote-menu.png' });
await browser.close();
