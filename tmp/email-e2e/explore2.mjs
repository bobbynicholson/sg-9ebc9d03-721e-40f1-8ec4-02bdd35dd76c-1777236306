import { chromium } from "@playwright/test";
import fs from "fs";
const cookies = JSON.parse(fs.readFileSync("tmp/email-e2e/.cookies.json", "utf8"));
const st = JSON.parse(fs.readFileSync("tmp/email-e2e/A.json", "utf8"));
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
await ctx.addCookies(cookies);
await ctx.route("**/*", (r) => (["GET", "HEAD", "OPTIONS"].includes(r.request().method()) || r.request().url().includes("/auth/v1/") ? r.continue() : r.abort()));
const page = await ctx.newPage();
await page.goto(`http://localhost:3001/raj267748-payfast-test/admin/orders?orderId=${st.order_id}`, { waitUntil: "domcontentloaded", timeout: 180000 });
await page.waitForTimeout(16000);
await page.getByRole("dialog").getByRole("button", { name: "Confirmed" }).click().catch(e => console.log("no Confirmed btn", e.message.slice(0,80)));
await page.waitForTimeout(1500);
console.log("after Confirmed click:", JSON.stringify(await page.locator("[role=menu] [role=menuitem], [role=listbox] [role=option], [role=menuitemradio]").allTextContents()));
await page.keyboard.press("Escape");
await page.getByRole("dialog").getByRole("button", { name: "Edit" }).click();
await page.waitForTimeout(2500);
const selects = await page.locator("[role=dialog] select, [role=dialog] [role=combobox]").evaluateAll(els => els.map(e => (e.id||"") + "|" + (e.getAttribute("aria-label")||"") + "|" + (e.textContent||"").trim().slice(0,40)));
console.log("edit selects:", JSON.stringify(selects));
await page.screenshot({ path: "tmp/email-e2e/order-edit.png" });
await browser.close();
